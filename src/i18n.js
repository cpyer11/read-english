  function normalizePreference(preference) {
    return Object.hasOwn(languages, preference) ? preference : "auto";
  }

  function matchLanguage(tag) {
    const value = String(tag || "").replaceAll("_", "-").toLowerCase();
    if (value.startsWith("zh")) {
      return /(?:^|-)hant(?:-|$)|(?:^|-)(tw|hk|mo)(?:-|$)/.test(value) ? "zh-TW" : "zh-CN";
    }
    const base = value.split("-")[0];
    return Object.hasOwn(languages, base) ? base : null;
  }

  function resolveLanguage(preference = "auto", browserLanguages) {
    const explicit = normalizePreference(preference);
    if (explicit !== "auto") return explicit;
    const candidates = browserLanguages || [
      globalThis.chrome?.i18n?.getUILanguage?.(),
      ...(globalThis.navigator?.languages || []),
    ];
    for (const tag of candidates) {
      const language = matchLanguage(tag);
      if (language) return language;
    }
    return "en";
  }

  function createTranslator(language) {
    const dictionary = Object.hasOwn(messages, language) ? messages[language] : messages.en;
    return (key, values = {}) => (dictionary[key] || messages.en[key] || key)
      .replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(values, name) ? String(values[name]) : placeholder);
  }

  function translateDocument(root, translate) {
    for (const element of root.querySelectorAll("[data-i18n]")) element.textContent = translate(element.dataset.i18n);
    for (const element of root.querySelectorAll("[data-i18n-aria]")) element.setAttribute("aria-label", translate(element.dataset.i18nAria));
  }

  globalThis.ULWI18n = Object.freeze({ languages, messages, normalizePreference, resolveLanguage, createTranslator, translateDocument });
